import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { root } from './content.mjs';

const catalogUrl = 'https://ignite.microsoft.com/en-US/sessions?liveAndUpcoming=0&filter=deliveryTypes%2FlogicalValue%3EOnline&filter=audienceTypes%2FlogicalValue%3ETechnical+Decision+Maker';
const apiUrl = 'https://ignite.microsoft.com/api/session/all/en-US';
const matchesCatalogFilters = (session) => session.deliveryTypes?.some((item) => item.logicalValue === 'Online')
  && session.audienceTypes?.some((item) => item.logicalValue === 'Technical Decision Maker');
const generatedMarker = '<!-- Generated by scripts/refresh-catalog.mjs; edit content/session-summaries.json for summaries. -->';
const curatedMarker = '<!-- Manually curated session; catalog refresh keeps this article. -->';
const checksumPattern = /<!-- Generated content SHA-256: ([a-f0-9]{64}) -->\n/;
const canonical = (text) => text.replace(/\r\n/g, '\n');
const checksum = (text) => createHash('sha256').update(canonical(text)).digest('hex');
const withChecksum = (text) => text.replace(generatedMarker, `${generatedMarker}\n<!-- Generated content SHA-256: ${checksum(text)} -->`);
const sessionSlug = (code) => {
  if (typeof code !== 'string' || !/^[A-Z]{2,}[0-9]+[A-Z]*$/.test(code)) throw new Error(`Invalid session code: ${code}`);
  return code === 'KEY01' ? 'opening-keynote' : code.toLowerCase();
};
const detailUrl = (session) => {
  if (typeof session.sessionInstanceId !== 'string' || !/^[a-zA-Z0-9-]+$/.test(session.sessionInstanceId)) {
    throw new Error(`Invalid session instance ID: ${session.sessionInstanceId}`);
  }
  return `https://ignite.microsoft.com/en-US/sessions/${session.sessionInstanceId}?source=sessions`;
};

const tableText = (value) => String(value ?? '').replace(/[\u200B\uFEFF]/g, '').replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
const markdownUrl = (value) => String(value).replaceAll('(', '%28').replaceAll(')', '%29');
const link = (label, value) => {
  try {
    const url = new URL(value);
    if (url.protocol !== 'https:') return null;
    const text = tableText(label).replace(/([\\[\]])/g, '\\$1');
    return `[${text}](${markdownUrl(url.toString())})`;
  } catch {
    return null;
  }
};

function formatTime(value) {
  if (!value) return '';
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Tokyo',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(new Date(value));
  const part = (type) => parts.find((item) => item.type === type)?.value ?? '';
  return `${part('year')}-${part('month')}-${part('day')} ${part('hour')}:${part('minute')}`;
}

function mediaLinks(session) {
  const links = [];
  if (session.onDemand) links.push(link('動画', session.onDemand));
  if (session.downloadVideoLink) links.push(link('MP4', session.downloadVideoLink));
  if (session.captionFileLink) links.push(link('字幕', session.captionFileLink));
  const validLinks = links.filter(Boolean);
  if (!validLinks.length) {
    if (session.viewingOptions?.some((item) => item.logicalValue === 'Will be recorded')) return '録画予定';
    if (session.viewingOptions?.some((item) => item.logicalValue === 'Will not be recorded')) return '録画なし';
    return '未掲載';
  }
  return validLinks.join(' / ');
}

function materialLinks(session) {
  const links = [];
  if (session.slideDeck) links.push(link('スライド', session.slideDeck));
  for (const resource of session.relatedResources ?? []) {
    if (resource.link) links.push(link(resource.label || resource.category || '関連資料', resource.link));
  }
  const validLinks = links.filter(Boolean);
  return validLinks.length ? validLinks.join(' / ') : '—';
}

export function createSessionMarkdown(instances, verifiedAt, summaries) {
  if (!instances.length) throw new Error('A session requires at least one instance');
  const first = instances[0];
  const slug = sessionSlug(first.sessionCode);
  if (instances.some((session) => session.sessionCode !== first.sessionCode)) throw new Error('Session instances must share a code');
  const summary = summaries.sessions[first.sessionCode]?.trim() || '公式カタログのセッションです。日本語の内容要約は確認中です。';
  const sources = [...new Set(instances.map(detailUrl))];
  const topics = [...new Set(instances.flatMap((session) => (session.topic ?? []).map((item) => item.displayValue)).filter(Boolean))];
  const speakers = [...new Set(instances.map((session) => session.speakerNames).filter(Boolean))].join(' / ') || '未掲載';
  const sessionRows = instances.map((session) => {
    const start = formatTime(session.startDateTime);
    const end = formatTime(session.endDateTime);
    const dateTime = start ? `${start}${end ? `–${end.slice(-5)}` : ''} JST` : '日時未掲載';
    return `| ${dateTime} | ${link('公式詳細', detailUrl(session))} | ${mediaLinks(session)} | ${materialLinks(session)} |`;
  });
  const article = `---
id: ${slug}
title: ${JSON.stringify(`${first.sessionCode}: ${first.title}`)}
summary: ${JSON.stringify(summary)}
content_type: session
topic: sessions
tags: [catalog]
last_verified: "${verifiedAt}"
official_sources:
${sources.map((source) => `  - ${JSON.stringify(source)}`).join('\n')}
---

${generatedMarker}

## 概要

${summary}

## セッション情報

| 項目 | 内容 |
| --- | --- |
| セッションコード | ${tableText(first.sessionCode)} |
| 登壇者 | ${tableText(speakers)} |
| トピック | ${tableText(topics.join('・') || '未掲載')} |
| 配信形式 | Online |

## 開催枠・動画・資料

| 開始日時 | 公式ページ | 動画 | 資料 |
| --- | --- | --- | --- |
${sessionRows.join('\n')}

## 確認範囲・注意点

日本語の要点は公式セッション説明と、掲載されている場合は Microsoft の AI 要約を基に整理しています（要約確認日 ${summaries.last_verified}）。動画の全編視聴や発言の逐語確認は行っていません。資料にはセッションのスライドに加え、関連する Web ページも含まれます。提供状況は公式情報を確認してください。

## 参考リンク

${sources.map((source, index) => `- ${link(instances.length > 1 ? `公式セッション詳細 ${index + 1}` : '公式セッション詳細', source)}`).join('\n')}
`;
  return withChecksum(article);
}

export function createCatalogMarkdown(sessions, verifiedAt, summaries = { sessions: {} }) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(verifiedAt)
    || !Number.isFinite(Date.parse(verifiedAt))
    || new Date(verifiedAt).toISOString().slice(0, 10) !== verifiedAt) {
    throw new Error(`Invalid verification date: ${verifiedAt}`);
  }
  const matches = sessions.filter(matchesCatalogFilters)
    .sort((a, b) => String(a.startDateTime ?? '').localeCompare(String(b.startDateTime ?? ''))
      || String(a.sessionCode ?? '').localeCompare(String(b.sessionCode ?? '')));
  const videoCount = matches.filter((session) => Boolean(session.onDemand)).length;
  const slideCount = matches.filter((session) => Boolean(session.slideDeck)).length;
  const resourceCount = matches.filter((session) => session.relatedResources?.some((resource) => resource.link)).length;
  const noRecordingCount = matches.filter((session) => !session.onDemand
    && session.viewingOptions?.some((item) => item.logicalValue === 'Will not be recorded')).length;
  const summaryCount = matches.filter((session) => summaries.sessions[session.sessionCode]?.trim()).length;
  const lines = matches.map((session) => {
    const start = formatTime(session.startDateTime);
    const end = formatTime(session.endDateTime);
    const dateTime = start ? `${start}${end ? `–${end.slice(-5)}` : ''} JST` : '日時未掲載';
    const topics = (session.topic ?? []).map((item) => item.displayValue).filter(Boolean).join('・') || '—';
    const summary = summaries.sessions[session.sessionCode]?.trim() || '要約未作成';
    const article = `[${tableText(session.title).replace(/([\\[\]])/g, '\\$1')}](./${sessionSlug(session.sessionCode)}.md)`;
    return `| ${tableText(session.sessionCode)} | ${article} | ${dateTime} | ${tableText(session.speakerNames || '—')} | ${tableText(topics)} | ${tableText(summary)} | ${mediaLinks(session)} | ${materialLinks(session)} |`;
  });
  return `---
id: session-catalog
title: Microsoft Ignite 2026 セッションカタログ（Online・Technical Decision Maker）
summary: 公式カタログの Online・Technical Decision Maker 条件に合うセッションの内容を日本語で整理し、録画、スライド、関連資料へのリンクを掲載します。
content_type: session
topic: sessions
tags: [catalog, agents]
last_verified: "${verifiedAt}"
official_sources:
  - "${catalogUrl}"
  - "${apiUrl}"
---

## 概要

Microsoft 公式セッションカタログから、配信形式 \`Online\` と対象者 \`Technical Decision Maker\` の両方に該当するセッション枠を収録しています。ライブ・開催予定とオンデマンドを含み、同じセッションコードの複数枠は開催日時ごとに掲載します。

${matches.length} 枠（動画公開 ${videoCount} 件、スライド公開 ${slideCount} 件、関連資料あり ${resourceCount} 件、録画なし ${noRecordingCount} 件）。確認日 ${verifiedAt} 時点のカタログ情報です。録画予定は公開済み動画と区別しています。

日本語の短い要点は ${summaryCount} 枠に掲載しています（要点の確認日 ${summaries.last_verified || '未記録'}）。一覧の要点は公式カタログ説明と、掲載されている場合は Microsoft の AI 要約を基にしています。個別記事の確認範囲は記事ごとに記載しています。詳細や提供状況はセッションのリンク先を確認してください。

## セッション一覧

| コード | セッション | 開始日時（JST） | 登壇者 | トピック | 内容の要約 | 動画 | 資料 |
| --- | --- | --- | --- | --- | --- | --- | --- |
${lines.join('\n')}

## 参考リンク

- [Microsoft Ignite セッションカタログ（Online・Technical Decision Maker）](${catalogUrl})
- [公式セッションカタログデータ](${apiUrl})
`;
}

export async function refreshCatalog({ base = root, fetcher = fetch, verifiedAt = new Date().toISOString().slice(0, 10) } = {}) {
  const response = await fetcher(apiUrl, { headers: { accept: 'application/json' } });
  if (!response.ok) throw new Error(`Session catalog request failed: HTTP ${response.status}`);
  const sessions = await response.json();
  if (!Array.isArray(sessions)) throw new Error('Session catalog response was not an array');
  const count = sessions.filter(matchesCatalogFilters).length;
  if (!count) throw new Error('No sessions matched the requested catalog filters');
  const summaries = JSON.parse(fs.readFileSync(path.join(base, 'content/session-summaries.json'), 'utf8'));
  if (!summaries.sessions || typeof summaries.sessions !== 'object' || Array.isArray(summaries.sessions)
    || !/^\d{4}-\d{2}-\d{2}$/.test(summaries.last_verified)
    || Object.values(summaries.sessions).some((value) => typeof value !== 'string' || !value.trim())) {
    throw new Error('Invalid session summaries');
  }
  const markdown = createCatalogMarkdown(sessions, verifiedAt, summaries);
  const groups = new Map();
  for (const session of sessions.filter(matchesCatalogFilters)) {
    const slug = sessionSlug(session.sessionCode);
    if (slug === 'opening-keynote') continue;
    if (!groups.has(slug)) groups.set(slug, []);
    groups.get(slug).push(session);
  }
  const articles = [...groups].map(([slug, instances]) => ({
    file: path.join(base, 'content/sessions', `${slug}.md`),
    content: createSessionMarkdown(instances, verifiedAt, summaries),
  }));
  const curated = new Set();
  for (const article of articles) {
    if (fs.existsSync(article.file)) {
      const existing = canonical(fs.readFileSync(article.file, 'utf8'));
      if (existing.includes(curatedMarker) && !existing.includes(generatedMarker)) {
        curated.add(article.file);
        continue;
      }
      const match = existing.match(checksumPattern);
      const intact = match
        ? existing.includes(generatedMarker) && checksum(existing.replace(checksumPattern, '')) === match[1]
        : existing === canonical(article.content.replace(checksumPattern, ''));
      if (!intact) throw new Error(`Refusing to overwrite manually maintained session: ${article.file}`);
    }
  }
  for (const article of articles) {
    if (!curated.has(article.file)) fs.writeFileSync(article.file, article.content, 'utf8');
  }
  fs.writeFileSync(path.join(base, 'content/sessions/session-catalog.md'), markdown, 'utf8');
  const infoPath = path.join(base, 'content/build-info.json');
  const info = JSON.parse(fs.readFileSync(infoPath, 'utf8'));
  if (verifiedAt > info.last_verified) {
    info.last_verified = verifiedAt;
    fs.writeFileSync(infoPath, `${JSON.stringify(info, null, 2)}\n`, 'utf8');
  }
  return { count, verifiedAt };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const result = await refreshCatalog();
  console.log(`Imported ${result.count} Online / Technical Decision Maker session entries (verified ${result.verifiedAt}).`);
}
